namespace SnakeArena.Shared.Protocol;

public static class ProtocolConstants
{
    /// <summary>Version sent in <see cref="JoinRequest"/> and in discovery datagrams.</summary>
    public const ushort Version = 1;

    /// <summary>Default TCP port of the game server (its UDP game socket uses the same number).</summary>
    public const int DefaultPort = 47000;

    /// <summary>UDP port on which servers answer LAN discovery probes.</summary>
    public const int DiscoveryPort = 47001;

    /// <summary>Maximum length of a frame body (type byte + payload) in bytes.</summary>
    public const int MaxFrameLength = 64 * 1024;

    /// <summary>Maximum length of a player name in characters.</summary>
    public const int MaxNameLength = 16;

    /// <summary>Maximum length of a chat message in characters.</summary>
    public const int MaxChatLength = 200;

    /// <summary>Sender name used in <see cref="ChatBroadcast"/> for notices generated by the server.</summary>
    public const string ServerSender = "*";

    /// <summary>How often a client sends <see cref="UdpHello"/> while it receives snapshots over UDP.</summary>
    public static readonly TimeSpan UdpHelloInterval = TimeSpan.FromMilliseconds(500);

    /// <summary>
    /// The server switches a client back to TCP snapshots when it has not received a valid <see cref="UdpHello"/>
    /// from it for this long; a client stops sending hellos when it has not received a UDP snapshot for this long.
    /// </summary>
    public static readonly TimeSpan UdpTimeout = TimeSpan.FromSeconds(2);
}
