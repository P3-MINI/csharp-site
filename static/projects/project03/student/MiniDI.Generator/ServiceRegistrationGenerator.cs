using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace MiniDI.Generator;

/// <summary>
/// Generates <c>MiniDI.Generated.GeneratedServices.AddGenerated(this ServiceCollection)</c>, which registers
/// every class marked with <c>[Service]</c> using reflection-free factories.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ServiceRegistrationGenerator : IIncrementalGenerator
{
    public const string ServiceAttributeName = "MiniDI.ServiceAttribute";
    public const string InjectAttributeName = "MiniDI.InjectAttribute";

    /// <summary>Name of the pipeline step producing the models (used by the caching test - do not change).</summary>
    public const string ModelsTrackingName = "ServiceModels";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<ServiceClassModel> models = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                ServiceAttributeName,
                predicate: static (node, _) => node is ClassDeclarationSyntax,
                transform: static (ctx, ct) => Analyze(ctx, ct))
            .WithTrackingName(ModelsTrackingName);

        context.RegisterSourceOutput(models.Collect(), static (spc, items) => Emit(spc, items));
    }

    /// <summary>
    /// Called for every class marked with [Service] (and again only when its file changes).
    /// </summary>
    private static ServiceClassModel Analyze(GeneratorAttributeSyntaxContext context, CancellationToken cancellationToken)
    {
        // TODO (Part 4): collect everything needed to emit the registrations and to report diagnostics:
        // the [Service] attributes (context.Attributes), the constructor and its parameters, problems found.
        // Store only equatable data in the model (strings, numbers, records, EquatableArray<T>, LocationInfo),
        // never ISymbol, SyntaxNode, Compilation or Location.
        var symbol = (INamedTypeSymbol)context.TargetSymbol;
        return new ServiceClassModel(symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<ServiceClassModel> services)
    {
        // TODO (Part 4): report diagnostics (DiagnosticDescriptors) and emit one registration per [Service] attribute.
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>");
        code.AppendLine("namespace MiniDI.Generated");
        code.AppendLine("{");
        code.AppendLine("    internal static class GeneratedServices");
        code.AppendLine("    {");
        code.AppendLine("        public static global::MiniDI.ServiceCollection AddGenerated(this global::MiniDI.ServiceCollection services)");
        code.AppendLine("        {");
        foreach (var service in services)
            code.AppendLine($"            // TODO: register {service.FullyQualifiedName}");
        code.AppendLine("            return services;");
        code.AppendLine("        }");
        code.AppendLine("    }");
        code.AppendLine("}");

        context.AddSource("GeneratedServices.g.cs", SourceText.From(code.ToString(), Encoding.UTF8));
    }
}

/// <summary>
/// The result of <c>Analyze</c> for one class. It must have value equality (records do), so that the
/// generator can reuse cached results when nothing relevant changed.
/// </summary>
// TODO (Part 4): extend the model (you may add more records, e.g. for registrations, parameters, diagnostics).
internal sealed record ServiceClassModel(string FullyQualifiedName);
